async page => {
  const results = { errors: [], requests: [], checks: [] };
  page.on('pageerror', error => results.errors.push(error.message));
  page.on('request', request => { if (request.method() === 'POST') results.requests.push(request.url()); });
  const shot = async name => page.screenshot({ path: 'game/review/1026-final-' + name + '.png' });
  const waitVillage = () => page.waitForFunction(() => window.__village?.player);
  await page.setViewportSize({ width: 360, height: 740 });
  await page.goto('http://127.0.0.1:5191/?pub&end&hour=11');
  await page.waitForFunction(() => window.__journey?.hillRoom && window.__journey?.hillOpen());
  await page.evaluate(() => { localStorage.clear(); window.__journey.toArch(); });
  await page.getByRole('button', { name: '다음', exact: true }).waitFor();
  for (let i = 0; i < 10 && await page.getByRole('button', { name: '다음', exact: true }).isVisible(); i++) {
    await page.getByRole('button', { name: '다음', exact: true }).click();
  }
  await page.getByRole('button', { name: '마을로 가기', exact: true }).click();
  await waitVillage();
  await page.locator('.g-notice').waitFor();
  await page.locator('.g-notice .g-talk').click();
  await page.screenshot({path:'game/review/1026-final-pub-welcome-360.png'});
  const welcome = await page.locator('.g-notice').innerText();
  if (!welcome.includes('창립행사에 오신 걸 환영')) throw new Error('환영 차례 실패');
  await page.getByRole('button', { name: '고마워요', exact: true }).click();
  await page.getByRole('button', { name: '다음', exact: true }).waitFor();
  await page.locator('.g-notice .g-talk').click();
  results.checks.push({ hub: await page.locator('.g-notice').innerText() });
  await shot('pub-hub-360');
  await page.getByRole('button', { name: '다음', exact: true }).click();
  await page.getByRole('button', { name: '다음', exact: true }).waitFor();
  await page.locator('.g-notice .g-talk').click();
  results.checks.push({ east: await page.locator('.g-notice').innerText() });
  await shot('pub-east-360');
  await page.getByRole('button', { name: '다음', exact: true }).click();
  await page.getByRole('button', { name: '둘러보기 마치기', exact: true }).waitFor();
  await page.locator('.g-notice .g-talk').click();
  results.checks.push({ west: await page.locator('.g-notice').innerText() });
  await shot('pub-west-360');
  await page.getByRole('button', { name: '둘러보기 마치기', exact: true }).click();
  await page.waitForFunction(() => !window.__village.showing && !window.__village.paused);
  await page.waitForTimeout(6000);
  const lights = await page.evaluate(() => {
    const scene = window.__village, root = scene.children.getByName('pub-string-lights');
    return { persistent:!!root, alpha:root?.alpha, bulbs:root?.list.filter(item => item.name === 'pub-bulb').length };
  });
  if (!lights.persistent || lights.bulbs !== 27) throw new Error('지속 등불 실패');
  results.checks.push(lights);
  // 실제 게임의 문 앞으로 이동해서 판이 열리는 경로.
  await page.evaluate(() => window.__village.jump('hub', () => window.__village.runtime.enter('hub')));
  await page.locator('.t-seal').waitFor();
  results.checks.push({ citizen: await page.locator('.t-seal').innerText(), condition:await page.locator('.t-issued').innerText(), saveVisible:await page.getByRole('button', { name:'시민증 저장·보내기',exact:true }).isVisible() });
  await shot('pub-citizen-360');
  await page.locator('.t-back').click();
  await page.evaluate(() => window.__village.jump('board', () => window.__village.runtime.enter('board')));
  await page.getByRole('heading', {name:'게임에 대해 한마디 남겨주세요', exact:true}).waitFor();
  await page.getByRole('textbox', {name:'한 줄 남기기',exact:true}).fill('걸으며 예산을 다시 생각했어요');
  await page.getByRole('button', {name:'남기기',exact:true}).click();
  await page.getByRole('status').filter({hasText:'고마워요. 남긴 글은 모아 두었어요.'}).waitFor();
  await page.getByRole('textbox', {name:'한 줄 남기기',exact:true}).fill('한 번 더 남겨요');
  await page.getByRole('button', {name:'남기기',exact:true}).click();
  const limited = await page.getByRole('status').innerText();
  if (!limited.includes('10분')) throw new Error('기기 도배 제한 실패');
  await shot('pub-feedback-360');
  results.checks.push({ limited, durable:await page.evaluate(() => Object.keys(localStorage)), postCount:results.requests.length });
  await page.locator('.t-back').click();
  await page.evaluate(() => window.__village.jump('cards', () => window.__village.runtime.enter('cards')));
  await page.getByRole('heading', {name:'춘천시 행정위반에 교부금 39억원 깎였다',exact:true}).waitFor();
  await page.locator('.v-cut-more summary').click();
  await page.getByRole('searchbox').fill('생태탐방로');
  await page.getByRole('link', {name:'관련 기사 원문',exact:true}).waitFor();
  await shot('pub-cuts-360');
  const list = await page.locator('.v-cut-list').innerText();
  if (!list.includes('39.09억 원')) throw new Error('춘천 정확한 감액 누락');
  results.checks.push({ cuts: list.slice(0,200) });
  await page.getByRole('searchbox').fill('없는사업zz');
  if (!(await page.locator('.v-cut-list').innerText()).includes('검색 결과가 없어요')) throw new Error('빈 결과 실패');
  const publicView = await page.request.get('http://127.0.0.1:5191/api/game/village');
  if ((await publicView.json()).notes.some(note => note.text.includes('예산을 다시'))) throw new Error('수집 의견 공개됨');
  await page.goto('http://127.0.0.1:5191/?pub');
  if ((await page.locator('.g-intro').innerText()).includes('주민 여섯')) throw new Error('옛 시작 문구 남음');
  results.checks.push({ initial:await page.locator('.g-intro').innerText() });
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('http://127.0.0.1:5191/?pub&village&hour=11');
  await waitVillage();
  await page.waitForFunction(() => window.__village.children.getByName('pub-string-lights'));
  results.checks.push({ reducedLights:await page.evaluate(() => window.__village.children.getByName('pub-string-lights').alpha) });
  await shot('pub-reduced-360');
  await page.emulateMedia({reducedMotion:'no-preference'});
  return results;
}
